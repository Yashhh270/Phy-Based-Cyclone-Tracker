def build_forecast_manager(sid, model, full_track_df, norm_stats, latlon_scale, device,
                             feature_cols=FEATURE_COLS, lookback=LOOKBACK, lead_hours=LEAD_HOURS):
    """
    Generates every forecast realization (one per real observed timestep), each with
    all 4 lead times x 3 quantiles. Returns a long-format dataframe:
    one row per (forecast_origin_time, target_time, quantile).
    """
    storm = full_track_df[full_track_df['SID']==sid].sort_values('ISO_TIME').reset_index(drop=True)
    n = len(storm)
    if n < lookback + 1:
        print(f"Storm too short ({n} points)")
        return pd.DataFrame()

    times = storm['ISO_TIME'].values
    feats_raw = storm[feature_cols].values.astype(np.float32)

    records = []
    model.eval()
    with torch.no_grad():
        for i in range(lookback - 1, n - 1):
            seq = feats_raw[i - lookback + 1 : i + 1]
            if np.isnan(seq).any():
                continue

            norm_ref_lat, norm_ref_lon = seq[0, 0], seq[0, 1]
            origin_lat, origin_lon = seq[-1, 0], seq[-1, 1]
            origin_time = times[i]

            rel_lat = (seq[:, 0] - norm_ref_lat) / latlon_scale
            rel_lon = (seq[:, 1] - norm_ref_lon) / latlon_scale
            wind    = (seq[:, 2] - norm_stats['wind_mean'])    / (norm_stats['wind_std']    + 1e-6)
            pres    = (seq[:, 3] - norm_stats['pres_mean'])    / (norm_stats['pres_std']    + 1e-6)
            speed   = (seq[:, 4] - norm_stats['speed_mean'])   / (norm_stats['speed_std']   + 1e-6)
            heading = (seq[:, 6] - norm_stats['heading_mean']) / (norm_stats['heading_std'] + 1e-6)
            dir_rad = np.deg2rad(seq[:, 5])
            dir_sin, dir_cos = np.sin(dir_rad), np.cos(dir_rad)
            wind_obs, is_interp = seq[:, 7], seq[:, 8]
            ustr = (seq[:, 9]  - norm_stats['ustr_mean']) / (norm_stats['ustr_std'] + 1e-6)
            vstr = (seq[:, 10] - norm_stats['vstr_mean']) / (norm_stats['vstr_std'] + 1e-6)

            x_in = np.stack([rel_lat, rel_lon, wind, pres, speed, dir_sin, dir_cos,
                              heading, wind_obs, is_interp, ustr, vstr], axis=1).astype(np.float32)
            x_in = torch.from_numpy(x_in).unsqueeze(0).to(device)
            raw_steer = torch.tensor([[seq[-1, 9], seq[-1, 10]]], dtype=torch.float32).to(device)

            out = model(x_in, raw_steer)
            pred_q = out['quantiles'].cpu().numpy()[0]  # (n_leads, n_q, 2)

            for lead_i, h in enumerate(lead_hours):
                target_time = pd.Timestamp(origin_time) + pd.Timedelta(hours=h)
                for q_i, q_label in enumerate(['q10','q50','q90']):
                    lat = pred_q[lead_i, q_i, 0] * latlon_scale + origin_lat
                    lon = pred_q[lead_i, q_i, 1] * latlon_scale + origin_lon
                    records.append({
                        'origin_time': origin_time, 'target_time': target_time,
                        'lead_hours': h, 'quantile': q_label, 'lat': lat, 'lon': lon
                    })

    return pd.DataFrame(records)


