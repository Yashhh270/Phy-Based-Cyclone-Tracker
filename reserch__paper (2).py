def build_rolling_prediction(
    sid,
    model,
    full_track_df,
    norm_stats,
    latlon_scale,
    device,
    feature_cols=FEATURE_COLS,
    lookback=LOOKBACK,
    lead_hours_to_show=6
):
    storm = (
        full_track_df[full_track_df['SID'] == sid]
        .sort_values('ISO_TIME')
        .reset_index(drop=True)
    )

    n = len(storm)

    if n < lookback + 1:
        print(f"Storm too short ({n} points) for a lookback of {lookback}")
        return pd.DataFrame(columns=['lat', 'lon', 'ISO_TIME'])

    lead_idx = LEAD_HOURS.index(lead_hours_to_show)

    times = storm['ISO_TIME'].values
    feats_raw = storm[feature_cols].values.astype(np.float32)

    rolling_preds = []

    model.eval()

    with torch.no_grad():

        for i in range(lookback - 1, n - 1):

            seq = feats_raw[i - lookback + 1:i + 1]

            if np.isnan(seq).any():
                continue

            # Reference used for input relative-position features
            norm_ref_lat = seq[0, 0]
            norm_ref_lon = seq[0, 1]

            rel_lat = (seq[:, 0] - norm_ref_lat) / latlon_scale
            rel_lon = (seq[:, 1] - norm_ref_lon) / latlon_scale

            # Forecast origin = latest observation t0
            origin_lat = seq[-1, 0]
            origin_lon = seq[-1, 1]

            # Normalize scalar features
            wind = (
                seq[:, 2] - norm_stats['wind_mean']
            ) / (norm_stats['wind_std'] + 1e-6)

            pres = (
                seq[:, 3] - norm_stats['pres_mean']
            ) / (norm_stats['pres_std'] + 1e-6)

            speed = (
                seq[:, 4] - norm_stats['speed_mean']
            ) / (norm_stats['speed_std'] + 1e-6)

            heading = (
                seq[:, 6] - norm_stats['heading_mean']
            ) / (norm_stats['heading_std'] + 1e-6)

            # Convert direction to circular representation
            dir_rad = np.deg2rad(seq[:, 5])
            dir_sin = np.sin(dir_rad)
            dir_cos = np.cos(dir_rad)

            wind_obs = seq[:, 7]
            is_interp = seq[:, 8]

            ustr = (
                seq[:, 9] - norm_stats['ustr_mean']
            ) / (norm_stats['ustr_std'] + 1e-6)

            vstr = (
                seq[:, 10] - norm_stats['vstr_mean']
            ) / (norm_stats['vstr_std'] + 1e-6)

            # Same 12-feature representation used during training
            x_in = np.stack([
                rel_lat,
                rel_lon,
                wind,
                pres,
                speed,
                dir_sin,
                dir_cos,
                heading,
                wind_obs,
                is_interp,
                ustr,
                vstr
            ], axis=1).astype(np.float32)

            x_in = torch.from_numpy(x_in).unsqueeze(0).to(device)

            # Raw steering at forecast origin
            raw_steer = torch.tensor(
                [[seq[-1, 9], seq[-1, 10]]],
                dtype=torch.float32
            ).to(device)

            # Model prediction
            out = model(x_in, raw_steer)

            # Shape:
            # (1, 4 leads, 3 quantiles, 2 coordinates)
            pred_q = out['quantiles'].cpu().numpy()[0]

            # Select requested lead and median q50
            pred_median_norm = pred_q[lead_idx, 1]

            # Convert normalized displacement back to real lat/lon
            pred_lat = (
                pred_median_norm[0] * latlon_scale
                + origin_lat
            )

            pred_lon = (
                pred_median_norm[1] * latlon_scale
                + origin_lon
            )

            rolling_preds.append({
                'lat': pred_lat,
                'lon': pred_lon,
                'ISO_TIME': times[i]
            })

    return pd.DataFrame(rolling_preds)

