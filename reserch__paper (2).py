# ---------------- windowing ----------------
LOOKBACK = 6
LEAD_HOURS = [6, 12, 24, 48]
FEATURE_COLS = ['LAT','LON','WIND_KT_FILLED','PRES_MB','STORM_SPEED','STORM_DIR',
                 'HEADING_CHANGE','WIND_OBSERVED','IS_INTERPOLATED','U_STEER','V_STEER']

def build_windows(df, feature_cols=FEATURE_COLS, lookback=LOOKBACK, lead_hours=LEAD_HOURS,
                   require_original_target=False):
    samples = []
    for sid, storm in df.groupby('SID'):
        storm = storm.sort_values('ISO_TIME').reset_index(drop=True)
        n = len(storm)
        if n < lookback + 1:
            continue
        times = storm['ISO_TIME'].values
        feats = storm[feature_cols].values.astype(np.float32)
        flags = storm['NEWDELHI_IFLAG'].values if 'NEWDELHI_IFLAG' in storm.columns else None
        for i in range(lookback - 1, n - 1):
            t0 = times[i]
            input_seq = feats[i - lookback + 1 : i + 1]
            if np.isnan(input_seq).any():
                continue
            targets, valid = [], True
            for h in lead_hours:
                target_time = t0 + np.timedelta64(h, 'h')
                future_idx = np.where(times > t0)[0]
                if len(future_idx) == 0:
                    valid = False; break
                diffs = np.abs((times[future_idx] - target_time).astype('timedelta64[m]').astype(int))
                closest = future_idx[np.argmin(diffs)]
                if diffs.min() > 90:
                    valid = False; break
                if require_original_target and flags is not None and flags[closest] != 'O':
                    valid = False; break
                targets.append([storm['LAT'].values[closest], storm['LON'].values[closest]])
            if not valid:
                continue
            samples.append({'SID': sid, 't0': t0, 'input': input_seq,
                             'target': np.array(targets, dtype=np.float32),
                             'lat0': storm['LAT'].values[i], 'lon0': storm['LON'].values[i]})
    return samples

