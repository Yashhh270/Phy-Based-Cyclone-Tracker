def assign_regime(row):
    if pd.isna(row['HEADING_CHANGE_ROLL']) or pd.isna(row['STORM_SPEED_ROLL']):
        return 'unknown'

    # weak/disorganized:
    if row['WIND_KT_FILLED'] < 34:
        return 'weak'

    # slow-moving:
    if row['STORM_SPEED_ROLL'] < 6:
        return 'slow'

    # sharp turn:
    if row['HEADING_CHANGE_ROLL'] > 50:
        return 'sharp_turn'

    # recurving:
    if row['HEADING_CHANGE_ROLL'] > 25:
        return 'recurving'

    return 'normal'

