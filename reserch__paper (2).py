# ---------------- dataset ----------------
class TCWindowDataset(Dataset):
    def __init__(self, windows, norm_stats, latlon_scale=LATLON_SCALE):
        self.windows = windows
        self.ns = norm_stats
        self.scale = latlon_scale

    def __len__(self):
        return len(self.windows)

    def __getitem__(self, idx):
        w = self.windows[idx]
        seq = w['input']
        lat0, lon0 = seq[0, 0], seq[0, 1]
        rel_lat = (seq[:, 0] - lat0) / self.scale
        rel_lon = (seq[:, 1] - lon0) / self.scale
        wind    = (seq[:, 2] - self.ns['wind_mean'])    / (self.ns['wind_std']    + 1e-6)
        pres    = (seq[:, 3] - self.ns['pres_mean'])    / (self.ns['pres_std']    + 1e-6)
        speed   = (seq[:, 4] - self.ns['speed_mean'])   / (self.ns['speed_std']   + 1e-6)
        heading = (seq[:, 6] - self.ns['heading_mean']) / (self.ns['heading_std'] + 1e-6)
        dir_rad = np.deg2rad(seq[:, 5])
