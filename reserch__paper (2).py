def pinball_loss(pred_quantiles, target, quantiles, lead_weights=None):
    # pred_quantiles: (batch, n_leads, n_q, 2), target: (batch, n_leads, 2)
    target_exp = target.unsqueeze(2)
    errors = target_exp - pred_quantiles

    losses = []
    for i, q in enumerate(quantiles):
        e = errors[:, :, i, :]
        losses.append(torch.max(q * e, (q - 1) * e))
    loss = torch.stack(losses, dim=2)  # (batch, n_leads, n_q, 2)

    if lead_weights is not None:
        # lead_weights: (n_leads,) -> reshape to broadcast across batch, quantile, lat/lon dims
        w = lead_weights.view(1, -1, 1, 1).to(loss.device)
        loss = loss * w

    return loss.mean()


def physics_reg_loss(physics_adjusted, baseline_from_steer, weight=0.01):
    # light regularization: discourage the residual from drifting arbitrarily far from the physics prior
    residual_magnitude = (physics_adjusted - baseline_from_steer).pow(2).mean()
    return weight * residual_magnitude


def train_one_epoch(model, loader, optimizer, quantiles, device, physics_weight=0.01, lead_weights=None):
    model.train()
    total_loss = 0.0
    for xb, yb, origin, raw_steer in loader:
        xb, yb, raw_steer = xb.to(device), yb.to(device), raw_steer.to(device)
        optimizer.zero_grad()

        out = model(xb, raw_steer)
        pred_q = out['quantiles']

        q_loss = pinball_loss(pred_q, yb, quantiles, lead_weights=lead_weights)  # <-- pass it here

        baseline = model.steering_baseline(raw_steer)
        p_loss = physics_reg_loss(out['physics_adjusted'], baseline, weight=physics_weight)

        loss = q_loss + p_loss
        loss.backward()
        optimizer.step()
        total_loss += loss.item() * xb.size(0)

    return total_loss / len(loader.dataset)


