class TCTrackModel(nn.Module):
    def __init__(self, n_features=N_FEATURES, hidden_size=128, expert_hidden=64,
                 n_leads=N_LEADS, n_regimes=N_REGIMES, quantiles=QUANTILES, dropout=0.2,
                 latlon_scale=5.0, dt_hours=6):
        super().__init__()
        self.n_leads = n_leads
        self.n_regimes = n_regimes
        self.quantiles = quantiles
        self.n_q = len(quantiles)
        self.latlon_scale = latlon_scale
        self.dt_hours = dt_hours
        self.register_buffer('lead_hours_t', torch.tensor([6., 12., 24., 48.]), persistent=False)
        self.steer_scale = nn.Parameter(torch.tensor([1.0, 1.0, 0.75, 0.5]))

        self.encoder = nn.GRU(input_size=n_features, hidden_size=hidden_size,
                               num_layers=2, batch_first=True, dropout=dropout)

        self.gate = nn.Sequential(
            nn.Linear(hidden_size, 64), nn.ReLU(), nn.Dropout(dropout),
            nn.Linear(64, n_regimes),
        )

        self.experts = nn.ModuleList([
            nn.Sequential(
                nn.Linear(hidden_size, expert_hidden), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(expert_hidden, n_leads * 2),
            ) for _ in range(n_regimes)
        ])

        self.physics_correction = nn.Sequential(
            nn.Linear(hidden_size + n_leads * 2, 64), nn.ReLU(),
            nn.Linear(64, n_leads * 2),
        )

        self.quantile_head = nn.Linear(hidden_size + n_leads * 2, n_leads * self.n_q * 2)

    def steering_baseline(self, raw_steer):
        # raw_steer: (batch, 2) -> [u_steer, v_steer] in m/s at the last input timestep
        u, v = raw_steer[:, 0], raw_steer[:, 1]
        leads = torch.arange(1, self.n_leads + 1, device=raw_steer.device).float()
        hours = self.lead_hours_t * self.steer_scale
        deg_per_ms_per_hour = 3600 / 111000  # m/s -> deg/hour, flat-earth approx

        dlat = (v.unsqueeze(1) * deg_per_ms_per_hour * hours.view(1, -1)) / self.latlon_scale
        dlon = (u.unsqueeze(1) * deg_per_ms_per_hour * hours.view(1, -1)) / self.latlon_scale

        baseline = torch.stack([dlat, dlon], dim=-1)  # (batch, n_leads, 2)
        return baseline.reshape(raw_steer.size(0), -1)

    def forward(self, x, raw_steer):
        _, h_n = self.encoder(x)
        h = h_n[-1]

        gate_weights = F.softmax(self.gate(h), dim=-1)
        expert_outputs = torch.stack([expert(h) for expert in self.experts], dim=1)
        combined = torch.sum(gate_weights.unsqueeze(-1) * expert_outputs, dim=1)

        baseline = self.steering_baseline(raw_steer)
        physics_input = torch.cat([h, combined], dim=-1)
        residual = self.physics_correction(physics_input)
        physics_adjusted = baseline + residual

        quantile_input = torch.cat([h, physics_adjusted], dim=-1)
        quantile_out = self.quantile_head(quantile_input).view(-1, self.n_leads, self.n_q, 2)

        return {'gate_weights': gate_weights, 'expert_outputs': expert_outputs,
                'physics_adjusted': physics_adjusted, 'quantiles': quantile_out}

